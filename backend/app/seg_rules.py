def transport_mode(hub):
    """按到货渠道仓返回 (运输方式名, 目标天)；口径同 route_check：空运15/海运35/卡航35"""
    h = str(hub or "")
    if "东南亚" in h:
        return "海运", 35
    if "欧洲" in h:
        return "空运/卡航", 15
    if "美国" in h:
        return "空运+海运", 35
    if "加拿大" in h or "墨西哥" in h or "美客多" in h:
        return "海运", 35
    return "空运", 15


def ship_class(mode_name):
    """空/海归类：方式名含"海运"归海运，其余归空运。"""
    return "海运" if "海运" in (mode_name or "") else "空运"


def default_seg_targets():
    """seg_targets 默认配置：{环节名: {target, available}}（留空段不进配置）。"""
    out = {}
    for dept, name, _n0, _n1, target, _owner, _note, is_gap in SEGS:
        if is_gap or dept == "__GAP__":
            continue
        out[name] = {"target": target, "available": True}
    out[L4[1]] = {"target": L4[3], "available": True}
    return out


def seg_meta():
    """段定义元数据（配置中心/前端展示用），保持 SEGS 顺序 + L4。"""
    out = []
    for dept, name, n0, n1, target, owner, note, is_gap in SEGS:
        out.append({
            "name": name, "dept": dept,
            "from": n0, "to": n1,
            "fromPart": NODES[n0][0], "toPart": NODES[n1][0],
            "defaultTarget": target, "owner": owner,
            "note": note, "gap": is_gap,
        })
    dept, name, n0, target, owner, note = L4
    out.append({
        "name": name, "dept": dept,
        "from": n0, "to": "发货末批(Part5)",
        "fromPart": NODES[n0][0], "toPart": "Part5",
        "defaultTarget": target, "owner": owner,
        "note": note, "gap": False,
    })
    return out


