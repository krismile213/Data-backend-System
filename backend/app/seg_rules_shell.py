def transport_mode(hub):
    """按到货渠道仓返回 (运输方式名, 目标天)；口径同手机膜：空运15/海运35/卡航35"""
    h = str(hub or "")
    if "东南亚" in h:
        return "海运", 35
    if "欧洲" in h:
        return "空运/卡航", 15
    if "美国" in h:
        return "空运+海运", 35
    if "加拿大" in h or "墨西哥" in h or "美客多" in h:
        return "海运", 35
    return "空运", 15


def ship_class(mode_name):
    """空/海归类：方式名含"海运"归海运，其余归空运。"""
    return "海运" if "海运" in (mode_name or "") else "空运"


